import {test,expect} from '@playwright/test'
test('reported source centres, candidate dates and planetographic limits remain separate from analysis inputs',async({page},info)=>{
 let posts=0;page.on('request',r=>{if(r.method()==='POST')posts++})
 await page.route('**/api/v1/health',r=>r.fulfill({json:{status:'ok',science_ready:false,dem_ready:false,kernels_ready:false,reason_codes:['SCIENCE_ENGINE_NOT_READY']}}))
 await page.goto('/')
 const catalog=page.getByRole('region',{name:'South Pole Site Explorer',exact:true})
 const card=(name:string)=>catalog.getByRole('article',{name,exact:true})
 await expect(card('Connecting Ridge')).toContainText('R01 / Site01: -89.4632° latitude, -137.49° source longitude')
 await expect(card('Connecting Ridge')).toContainText('222.51°E')
 await expect(card('Connecting Ridge')).toContainText('2022-08-19')
 await expect(card('Shackleton Rim')).toContainText('R04 / Site04: -89.7668° latitude, -171.87° source longitude')
 await expect(card('Shackleton Rim')).toContainText('188.13°E')
 await expect(card('Shackleton Rim')).not.toContainText('Historical candidate reference:')
 await expect(card('Mons Mouton')).toContainText('Planetographic')
 await expect(card('Mons Mouton')).toContainText('LOLA 2011')
 await expect(card('Mons Mouton')).toContainText('2024-10-28')
 await expect(card('Mons Mouton Plateau')).toContainText('2024-10-28')
 await expect(card('Site01 / CR1 Research Point')).toContainText('-89.468° latitude, 222.6° east')
 for(const name of ['Connecting Ridge','Shackleton Rim','Mons Mouton','Mons Mouton Plateau'])await expect(card(name).getByRole('button',{name:/View on Globe/})).toBeDisabled()
 for(const b of await catalog.getByRole('button',{name:/Use These Coordinates/}).all())await expect(b).toBeDisabled()
 await page.getByLabel('Latitude (degrees)',{exact:true}).fill('-85')
 await page.getByLabel('Longitude (degrees east)',{exact:true}).fill('30')
 await card('Mons Mouton').getByRole('button',{name:/Inspect/}).focus();await page.keyboard.press('Enter')
 await expect(card('Mons Mouton')).toContainText('Command 10: BLOCKED_403')
 await expect(card('Mons Mouton')).toContainText('not independently reverified in this task')
 await page.getByLabel('Source reference coordinate — Connecting Ridge',{exact:true}).screenshot({path:info.outputPath('Evidence-R01.png')})
 await page.getByLabel('Source reference coordinate — Mons Mouton',{exact:true}).screenshot({path:info.outputPath('Evidence-planetographic.png')})
 await page.addStyleTag({content:'html{font-size:200%}'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByLabel('Source reference coordinate — Shackleton Rim',{exact:true}).screenshot({path:info.outputPath('Evidence-R04-200.png')})
 await expect(page.getByLabel('Latitude (degrees)',{exact:true})).toHaveValue('-85')
 await expect(page.getByLabel('Longitude (degrees east)',{exact:true})).toHaveValue('30')
 expect(posts).toBe(0)
})
