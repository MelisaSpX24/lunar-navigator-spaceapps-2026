import {test,expect} from '@playwright/test'
test('compact cards disclose complete source chain and exact unlock requirements without changing mission inputs',async({page},info)=>{
 let posts=0;page.on('request',r=>{if(r.method()==='POST')posts++})
 await page.route('**/api/v1/health',r=>r.abort());await page.goto('/')
 const catalog=page.getByRole('region',{name:'South Pole Site Explorer',exact:true})
 const cards=catalog.getByRole('article')
 await expect(cards).toHaveCount(5)
 for(const card of await cards.all()){
  await expect(card.locator('details')).not.toHaveAttribute('open','')
  await expect(card.getByRole('button',{name:/Use These Coordinates/})).toBeDisabled()
  await expect(card.getByText('Scientific Coverage Unknown · Analysis Unavailable',{exact:true})).toBeVisible()
 }
 const ridge=catalog.getByRole('article',{name:'Connecting Ridge',exact:true})
 await ridge.screenshot({path:info.outputPath('Final-compact-R01.png')})
 await ridge.getByRole('button',{name:/Inspect/}).focus();await page.keyboard.press('Enter')
 await expect(ridge.locator('details')).toHaveAttribute('open','')
 await ridge.locator('summary').click();await expect(ridge.locator('details')).not.toHaveAttribute('open','')
 await ridge.getByRole('button',{name:/Inspect/}).click();await expect(ridge.locator('details')).toHaveAttribute('open','')
 await expect(ridge).toContainText('Document ID: 20230007818')
 await expect(ridge).toContainText('Document ID: 20250002845')
 await expect(ridge).toContainText('A2.1-1, page 75')
 await expect(ridge).toContainText('Version 4, 14 May 2008')
 await expect(ridge.getByRole('heading',{name:'Evidence needed to unlock'})).toBeVisible()
 await page.getByLabel('Latitude (degrees)',{exact:true}).fill('-85')
 await page.getByLabel('Longitude (degrees east)',{exact:true}).fill('30')
 const cr1=catalog.getByRole('article',{name:'Site01 / CR1 Research Point',exact:true})
 await cr1.getByRole('button',{name:/Inspect/}).click()
 await expect(cr1).toContainText('20220015275')
 await expect(cr1).toContainText('C1 / CR1')
 await page.addStyleTag({content:'html{font-size:200%}'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 // Capture a closed card to inspect the final hierarchy at enlarged text.
 const plateau=catalog.getByRole('article',{name:'Mons Mouton Plateau',exact:true})
 await plateau.screenshot({path:info.outputPath('Final-compact-plateau-200.png')})
 await expect(page.getByLabel('Latitude (degrees)',{exact:true})).toHaveValue('-85')
 await expect(page.getByRole('button',{name:'Run Analysis',exact:true})).toBeDisabled()
 expect(posts).toBe(0)
})
