import { test,expect,type Page } from '@playwright/test'
const catalog=(p:Page)=>p.getByRole('region',{name:'South Pole Site Explorer',exact:true})
const cr1=(p:Page)=>p.getByRole('article',{name:'Site01 / CR1 Research Point',exact:true})
const globe=(p:Page)=>p.getByRole('region',{name:'Global lunar view',exact:true})
async function start(p:Page){await p.route('**/api/v1/health',r=>r.fulfill({json:{status:'ok',science_ready:false,dem_ready:false,kernels_ready:false,reason_codes:['SCIENCE_ENGINE_NOT_READY']}}));await p.goto('/');await expect(p.getByLabel('Camera view',{exact:true})).toContainText('3D scene ready')}
test('catalog sources, exploration gates and visual-only focus preserve mission fields and readiness',async({page},info)=>{
 let posts=0;page.on('request',r=>{if(r.method()==='POST')posts++})
 await start(page)
 await page.getByLabel('Latitude (degrees)',{exact:true}).fill('-85');await page.getByLabel('Longitude (degrees east)',{exact:true}).fill('30')
 await page.getByLabel('UTC date',{exact:true}).fill('2026-11-14');await page.getByLabel('UTC time',{exact:true}).fill('12:30')
 await catalog(page).screenshot({path:info.outputPath('Sites-list.png')})
 await expect(catalog(page).getByRole('button',{name:/Use These Coordinates/})).toHaveCount(5)
 for(const b of await catalog(page).getByRole('button',{name:/Use These Coordinates/}).all())await expect(b).toBeDisabled()
 await cr1(page).getByRole('button',{name:/View on Globe/}).click()
 await expect(page.getByLabel('Camera view',{exact:true})).toContainText('View latitude -89.5°')
 await expect(page.getByLabel('Camera view',{exact:true})).toContainText('View longitude -137.4°')
 await expect(page.getByLabel('Latitude (degrees)',{exact:true})).toHaveValue('-85')
 await expect(page.getByLabel('Longitude (degrees east)',{exact:true})).toHaveValue('30')
 await expect(page.getByLabel('UTC time',{exact:true})).toHaveValue('12:30')
 await expect(page.getByRole('button',{name:'Run Analysis',exact:true})).toBeDisabled()
 await globe(page).screenshot({path:info.outputPath('Sites-CR1-focus.png')})
 await page.getByRole('button',{name:'Reset View',exact:true}).click()
 await page.getByRole('button',{name:'Focus South Pole',exact:true}).click()
 await globe(page).screenshot({path:info.outputPath('Sites-south.png')})
 expect(posts).toBe(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('real marker raycast inspects sources without selecting the sphere; custom edits and reset stay authoritative',async({page})=>{
 await start(page);await cr1(page).getByRole('button',{name:/View on Globe/}).click()
 const canvas=page.getByLabel('Interactive 3D lunar sphere',{exact:true}).locator('canvas')
 if(page.viewportSize()!.width<=700)await page.getByRole('button',{name:'Enable globe interaction',exact:true}).click()
 const box=(await canvas.boundingBox())!
 await page.mouse.click(box.x+box.width/2,box.y+box.height/2)
 await expect(cr1(page).getByRole('button',{name:/Inspect/})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByLabel('Latitude (degrees)',{exact:true})).toHaveValue('')
 await expect(page.getByLabel('Longitude (degrees east)',{exact:true})).toHaveValue('')
 await page.getByLabel('Latitude (degrees)',{exact:true}).fill('-84');await page.getByLabel('Longitude (degrees east)',{exact:true}).fill('270')
 await expect(catalog(page)).toContainText('Custom coordinates / no verified catalog match')
 await page.getByRole('navigation').getByRole('link',{name:'Mission Analysis',exact:true}).click()
 await page.getByRole('navigation').getByRole('link',{name:'Mission Setup',exact:true}).click()
 await expect(page.getByLabel('Longitude (degrees east)',{exact:true})).toHaveValue('270')
 await page.getByRole('button',{name:'Reset scenario',exact:true}).click()
 await expect(page.getByLabel('Latitude (degrees)',{exact:true})).toHaveValue('')
})
test('WebGL unavailable and 200 percent text retain catalog, numeric form, sources and keyboard access',async({page},info)=>{
 await page.addInitScript(()=>{HTMLCanvasElement.prototype.getContext=function(){return null} as typeof HTMLCanvasElement.prototype.getContext})
 await page.route('**/api/v1/health',r=>r.abort());await page.goto('/')
 await expect(page.getByText('WebGL unavailable',{exact:true}).first()).toBeVisible()
 await page.getByLabel('Latitude (degrees)',{exact:true}).fill('-85')
 await page.addStyleTag({content:'html{font-size:200%}'})
 await cr1(page).getByRole('button',{name:/Inspect/}).focus();await page.keyboard.press('Enter')
 await expect(cr1(page).getByRole('button',{name:/Inspect/})).toHaveAttribute('aria-pressed','true')
 await expect(cr1(page)).toContainText('NOT VERIFIED')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await cr1(page).screenshot({path:info.outputPath('Sites-200-no-WebGL.png')})
})
